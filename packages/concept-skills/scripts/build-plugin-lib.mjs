#!/usr/bin/env node
// Regenerates the concept-skills plugin's CJS lib from src/.
//
//   pnpm --filter @repo/concept-skills build:plugin-lib
//
// The plugin's CLI runs under bare `node` with no node_modules, so it cannot import this package;
// the lib is a generated bundle, committed because a plugin ships by file copy.
//
// IT FAILS QUIETLY: if it stops producing correct output the committed .cjs keeps working and the
// tests stay green, while an edit to src/ stops reaching the plugin. After changing anything here,
// re-run it and read `git diff plugins/concept-skills/scripts/lib/`.

import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const defaultOutDir = path.resolve(pkgRoot, "../../plugins/concept-skills/scripts/lib");

// Pinned so the `// <path>` comments esbuild stamps do not depend on where the build was launched
// from, and so `strict` in the tsconfig (which makes it emit "use strict") is always the one read.
const absWorkingDir = pkgRoot;
const tsconfig = path.join(pkgRoot, "tsconfig.json");

const BANNER = `// GENERATED by packages/concept-skills/scripts/build-plugin-lib.mjs — DO NOT EDIT.
// Source: packages/concept-skills/src/index.ts
// Regenerate with: pnpm --filter @repo/concept-skills build:plugin-lib`;

/** Build the lib into `outDir` (default: the committed plugin directory). Exported for tests. */
export async function buildPluginLib(outDir = defaultOutDir) {
  const outfile = path.join(outDir, "concept-skills.cjs");
  await build({
    absWorkingDir,
    tsconfig,
    // Resolved to this checkout's own source, not through a node_modules symlink that may point at
    // another checkout (which would make the bundle's bytes depend on where the repo lives).
    alias: { "@repo/claude-fs": path.resolve(pkgRoot, "../claude-fs/src/index.ts") },
    entryPoints: [path.join(pkgRoot, "src/index.ts")],
    outfile,
    bundle: true,
    platform: "node",
    target: "node22",
    format: "cjs",
    external: ["node:fs", "node:path", "node:os", "fs", "path", "os"],
    banner: { js: BANNER },
    legalComments: "none",
  });
  return outfile;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const outfile = await buildPluginLib();
  process.stdout.write(`built ${path.relative(process.cwd(), outfile)}\n`);
}
