#!/usr/bin/env node
// Regenerates the plugin's pure runtime libs from src/core.
//
// Why this exists: successPathSteps, the managed-region helpers and the first-install seed are
// needed BOTH by the desktop app and by the standalone scripts the plugin ships (some of which a
// project copies into .claude/scripts/, all of which run outside this workspace). Those
// scripts must run under bare `node` with no node_modules, so they cannot import anything from
// here. Rather than maintain two implementations that silently drift, src/core is the source and
// these are generated CJS bundles.
//
//   pnpm --filter maestro build:plugin-libs
//
// The generated files are committed — a project installs them by file copy, so they have to be
// present in the repo, not produced at install time.
//
// THIS SCRIPT IS LOAD-BEARING, AND IT FAILS QUIETLY. If it stops producing correct output, the
// committed .cjs files keep working and every test keeps passing; the symptom is that an edit to
// a source module stops reaching the plugin, and the hooks go on running the old behaviour. So
// after changing anything here, re-run it and read `git diff plugins/maestro/scripts/lib/`
// rather than trusting a green suite.

import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const outDir = path.resolve(appRoot, "../../plugins/maestro/scripts/lib");

// esbuild stamps a `// <path>` comment above each module it bundles, relative to its working
// directory — so the bundle's bytes depend on where the build was launched from. Pinned to the
// app root rather than left as `process.cwd()`, which makes `pnpm --filter maestro
// build:plugin-libs` and `node apps/maestro/scripts/build-plugin-libs.mjs` from the repo root
// produce the same file instead of a spurious diff for whoever runs the other one.
const absWorkingDir = appRoot;

// The tsconfig esbuild reads is likewise pinned rather than discovered. It walks up from the entry
// point looking for one, and `strict` there is what makes it emit `"use strict";` at the top of a
// CJS bundle. The move changed which file that walk finds — `packages/maestro-core/tsconfig.json`
// (strict) became `apps/maestro/tsconfig.json` (a solution file: `files: []`, references only, no
// compilerOptions at all) — and the bundles silently came out non-strict. Nothing fails when that
// happens: the hooks keep running, they just stop throwing on the assignments strict mode catches.
// tsconfig.node.json is the project that actually owns src/core.
const tsconfig = path.join(appRoot, "tsconfig.node.json");

const BANNER = `// GENERATED by apps/maestro/scripts/build-plugin-libs.mjs — DO NOT EDIT.
// Source: apps/maestro/src/core/plugin-entries/%NAME%.ts
// Regenerate with: pnpm --filter maestro build:plugin-libs`;

const entries = [
  { name: "maestro-session", entry: "src/core/plugin-entries/maestro-session.ts" },
  { name: "maestro-skill-regions", entry: "src/core/plugin-entries/maestro-skill-regions.ts" },
  { name: "maestro-seed", entry: "src/core/plugin-entries/maestro-seed.ts" },
  { name: "maestro-skill-tags", entry: "src/core/plugin-entries/maestro-skill-tags.ts" },
  { name: "maestro-report-defaults", entry: "src/core/plugin-entries/maestro-report-defaults.ts" },
  { name: "maestro-project-tags", entry: "src/core/plugin-entries/maestro-project-tags.ts" },
  { name: "maestro-agent-project-tags", entry: "src/core/plugin-entries/maestro-agent-project-tags.ts" },
  { name: "maestro-agent-types", entry: "src/core/plugin-entries/maestro-agent-types.ts" },
  { name: "maestro-concept-skills", entry: "src/core/plugin-entries/maestro-concept-skills.ts" },
  { name: "maestro-agent-sync", entry: "src/core/plugin-entries/maestro-agent-sync.ts" },
  { name: "maestro-handoff-defaults", entry: "src/core/plugin-entries/maestro-handoff-defaults.ts" },
  { name: "maestro-workflow-spec", entry: "src/core/plugin-entries/maestro-workflow-spec.ts" },
];

for (const { name, entry } of entries) {
  await build({
    absWorkingDir,
    tsconfig,
    entryPoints: [path.join(appRoot, entry)],
    outfile: path.join(outDir, `${name}.cjs`),
    bundle: true,
    platform: "node",
    target: "node22",
    format: "cjs",
    // Node built-ins stay external: the bundle must not inline a shim for fs/path/os/sqlite.
    // node:sqlite is what makes maestro-skill-tags.cjs degrade gracefully on an older `node` on
    // the session's PATH — externalizing it means the require() that can throw stays a require()
    // in the output, for the script's own try/catch to catch, rather than an inlined shim that
    // would throw at a different, harder-to-catch point.
    external: ["node:fs", "node:path", "node:os", "node:sqlite", "fs", "path", "os"],
    banner: { js: BANNER.replace("%NAME%", name) },
    legalComments: "none",
  });
  process.stdout.write(`built ${path.relative(process.cwd(), path.join(outDir, `${name}.cjs`))}\n`);
}
